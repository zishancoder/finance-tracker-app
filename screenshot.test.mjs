import assert from 'node:assert/strict';
import { extractTransaction, parseExpenseDate, localDate } from './screenshot.ts';
const gpay = extractTransaction('Google Pay\nTo Corner Cafe\n₹250.50\nPaid\n24 Oct 2026, 10:15 AM\nUPI transaction ID\n123456789012');
assert.equal(gpay.amount, '250.50');
assert.equal(gpay.title, 'Corner Cafe');
assert.equal(gpay.date, '2026-10-24');
assert.equal(gpay.blockedReason, '');
const phonepe = extractTransaction('PhonePe\nTransaction Successful\nRs. 1,25,000.00\nPaid to\nTest Merchant\n24 October 2026');
assert.equal(phonepe.amount, '125000.00');
assert.equal(phonepe.title, 'Test Merchant');
assert.equal(phonepe.date, '2026-10-24');
const paytm = extractTransaction('Paytm\nPaid to Test Shop\nINR 1,250\n24/09/2026\nTransaction ID 345678901234');
assert.equal(paytm.amount, '1250.00');
assert.equal(paytm.date, '2026-09-24');
assert.equal(extractTransaction('₹\n25\nOct 24, 2026').amount, '25.00');
assert.equal(extractTransaction('Amount paid\n250.00').amount, '250.00');
assert.equal(extractTransaction('Paid to Corner Cafe\n250.50\nPayment successful\nUPI transaction ID\n123456').amount, '250.50');
assert.equal(extractTransaction('Payment successful\nTransaction ID\n123456').amount, '');
assert.equal(extractTransaction('Amount paid\n12,34').amount, '');
assert.equal(extractTransaction('UPI ID\n123456789012\n10:15\nBalance\n4000').amount, '');
assert.equal(extractTransaction('₹500\nBalance ₹1000').amount, '');
assert.equal(extractTransaction('₹500\nPaid ₹500').amount, '500.00');
assert.equal(extractTransaction('₹12,34').amount, '');
assert.equal(extractTransaction('₹250.001').amount, '');
for (const status of ['Failed', 'Pending', 'Processing', 'Received from John', 'Payment received', 'Refunded']) assert(extractTransaction('₹100\n'+status).blockedReason, status);
assert.equal(extractTransaction('$100\nAmount\n100').amount, '');
assert.equal(extractTransaction('₹10\n30 Feb 2026').date, '');
assert.equal(extractTransaction('₹10\n24 Oct 2026\n25 Oct 2026').date, '');
assert.equal(parseExpenseDate('2026-02-30'), null);
assert.equal(parseExpenseDate('2026-13-01'), null);
assert.equal(localDate(parseExpenseDate('2024-02-29')), '2024-02-29');
assert.equal(parseExpenseDate('24/10/2026'), null);
console.log('Screenshot parsing: sample payment layouts, exact amounts, recipients, dates, ambiguity, and non-expense checks passed.');
